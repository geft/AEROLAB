#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// Read package.json
const pkgPath = path.join(rootDir, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));

// Determine version: explicit override, release tag, then package.json.
// package.json is authoritative for local builds, because
// scripts/package-chromium-free.js names the installer from it — preferring the
// newest git tag here made the app footer report the previous release (v1.0.22)
// while the installer was named AEROLAB-Setup-v1.1.0.exe. The tag is kept as a
// last resort for a checkout whose package.json carries no version at all.
let version = pkg.version ? String(pkg.version).trim() : '';
if (process.env.APP_VERSION) {
  version = process.env.APP_VERSION.replace(/^v/, '');
} else if (process.env.GITHUB_REF_NAME && process.env.GITHUB_REF_NAME.startsWith('v')) {
  version = process.env.GITHUB_REF_NAME.replace(/^v/, '');
} else if (!version) {
  try {
    const gitTag = execSync('git describe --tags --abbrev=0', { cwd: rootDir, stdio: ['pipe', 'pipe', 'ignore'] })
      .toString()
      .trim();
    if (gitTag && gitTag.startsWith('v')) {
      version = gitTag.replace(/^v/, '');
    }
  } catch {}
}
if (!version) version = '1.0.0';

// Determine git commit hash
let gitCommit = 'local';
try {
  if (process.env.GITHUB_SHA) {
    gitCommit = process.env.GITHUB_SHA.slice(0, 7);
  } else {
    gitCommit = execSync('git rev-parse --short HEAD', { cwd: rootDir, stdio: ['pipe', 'pipe', 'ignore'] })
      .toString()
      .trim();
  }
} catch {
  gitCommit = 'dev';
}

// Determine git branch / ref
let gitBranch = 'main';
try {
  if (process.env.GITHUB_REF_NAME) {
    gitBranch = process.env.GITHUB_REF_NAME;
  } else {
    gitBranch = execSync('git rev-parse --abbrev-ref HEAD', { cwd: rootDir, stdio: ['pipe', 'pipe', 'ignore'] })
      .toString()
      .trim();
  }
} catch {
  gitBranch = 'main';
}

const buildTimestamp = new Date().toISOString();
const buildDate = buildTimestamp.split('T')[0];
const buildNumber = process.env.GITHUB_RUN_NUMBER || 'local';
const isRelease = Boolean(
  process.env.GITHUB_REF_NAME?.startsWith('v') ||
  process.env.NODE_ENV === 'production'
);

const buildInfo = {
  version,
  gitCommit,
  gitBranch,
  buildDate,
  buildTimestamp,
  buildNumber,
  isRelease
};

// 1. Generate src/frontend/version.ts
const versionTsContent = `// Auto-generated by scripts/generate-build-info.js - Do not edit directly
export interface BuildInfo {
  version: string;
  gitCommit: string;
  gitBranch: string;
  buildDate: string;
  buildTimestamp: string;
  buildNumber: string;
  isRelease: boolean;
}

export const BUILD_INFO: BuildInfo = ${JSON.stringify(buildInfo, null, 2)};
`;

const frontendVersionPath = path.join(rootDir, 'src', 'frontend', 'version.ts');
fs.writeFileSync(frontendVersionPath, versionTsContent, 'utf8');
console.log(`🏷️ Build info generated: v${version} (${gitCommit}) [${buildDate}] -> ${frontendVersionPath}`);

// 2. If dist-backend exists or data directory exists, generate version.json for backend
const distBackendDir = path.join(rootDir, 'dist-backend');
if (fs.existsSync(distBackendDir)) {
  fs.writeFileSync(
    path.join(distBackendDir, 'version.json'),
    JSON.stringify(buildInfo, null, 2),
    'utf8'
  );
}
